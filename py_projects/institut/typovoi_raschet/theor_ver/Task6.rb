# Задача 6. По данным независимых равноточных измерений физической величины a
# оценить истинное значение измеряемой величины и точность измерений с надежностью gamma.
# Вариант 1: gamma = 0.95, результаты измерений занесены ниже.

#Я оцениваю среднее, дисперсию и строю доверительный интервал. Если sigma(среднее квадратическое отклонение) известна - нормальное распределение. Если sigma неизвестна и выборка малая - Стьюдент.

# data - данные из варианта, выборка маленькая.
DATA_TASK6 = [2.1, 2.1, 3.2, 2.5, 2.1, 2.9, 2.8, 3.1, 4.3,
              2.8, 4.0, 2.3, 2.7, 2.4, 2.4, 2.3, 2.4, 2.9]

def main(data = DATA_TASK6)
  # len(data)-1 - степени свободы для таблицы Стьюдента.
  puts(data.length - 1)
  # n - количество чисел в выборке.
  n = data.length
  # gamma - доверительная вероятность.
  gamma = 0.95
  # X - среднее по выборке, центр интервала.
  x = StatisticsHelper.mean(data)
  # S - дисперсия. Для интервала среднего обычно нужен корень из нее.
  s = StatisticsHelper.variance(data, sample: true, center: x)
  # t - число из таблицы Стьюдента.
  t = 2.13
  puts format("%.5f", s)
  # delta - отступ от среднего до границы интервала.
  delta = t * s / Math.sqrt(n)
  puts format("%.5f", x)
  puts format("%.5f", delta)
  puts format("границы довер. инервала: %.5f; %.5f", x - delta, x + delta)
end

main if __FILE__ == $PROGRAM_NAME
