# Задание 15. В двух сериях испытаний проверить гипотезу о равенстве вероятностей
# благоприятного исхода при конкурирующей гипотезе об их неравенстве.
# В ответе привести вычисленное значение критерия, критическое значение и вывод.
# Вариант 1: alpha = 0.01, n1 = 500, m1 = 208, n2 = 1000, m2 = 433.

#Я проверяю гипотезы: дисперсии через Фишера, средние через Z/t, доли через критерий для двух вероятностей

def main(n1 = 500, m1 = 208, n2 = 1000, m2 = 433, alpha = 0.01)
  # n1 и n2 - сколько испытаний было в двух сериях.
  # m1 и m2 - сколько раз был нужный результат.
  # p1 и p2 - доли успехов в двух сериях.
  p1 = m1.to_f / n1
  p2 = m2.to_f / n2
  # p - общая доля успехов по двум сериям вместе.
  p = (m1 + m2).to_f / (n1 + n2)
  # t - посчитанный критерий для сравнения двух долей.
  t = (p1 - p2) / Math.sqrt(p * (1 - p) * (1.0 / n1 + 1.0 / n2))
  # t_crit - критическое значение из таблицы.
  t_crit = StatisticsHelper.normal_ppf((1 - alpha) / 2.0 + 0.5)
  puts "#{t} #{t_crit}"
  puts(t.abs < t_crit ? "– нет оснований отвергнуть гипотезу" : "– гипотезу отвергают.")
end

main if __FILE__ == $PROGRAM_NAME
