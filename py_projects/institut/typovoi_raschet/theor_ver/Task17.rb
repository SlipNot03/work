# Задание 17. Решить задачу на ранговый коэффициент Спирмена.
# Вариант 1: рейтинги шести банков оценены двумя экспертами.
# Нужно найти тесноту связи между оценками и сделать вывод о согласованности оценок экспертов.

#Я анализирую связь: Пирсон, Спирмен, регрессия, МНК, R2( коэффициент детерминации), ковариация

# x - первый ряд рангов/значений.
X_TASK17 = [7, 8, 9, 5, 6, 7]
# y - второй ряд рангов/значений.
Y_TASK17 = [3, 8, 8, 6, 3, 9]

def main(data_x = X_TASK17, data_y = Y_TASK17)
  # r - коэффициент Спирмена, сначала беру 1 и потом вычитаю поправки.
  r = 1.0
  # n - сколько пар значений.
  n = data_x.length
  n.times do |i|
    # i - номер пары; тут считаю квадрат разности рангов.
    r -= 6.0 / (n * (n**2 - 1)) * (data_x[i] - data_y[i])**2
  end
  # r_crit - критическое значение Спирмена из таблицы.
  r_crit = SpirmeTable.get_data(0.05, n)
  puts r
  puts(r.abs < r_crit ? "Принять гипотезу" : "Отклонить гипотезу")
end

