# Задание 4. По данным выборки, удовлетворяющей нормальному закону распределения, вычислить:
# 1) выборочное среднее;
# 2) исправленное выборочное среднее квадратическое отклонение;
# 3) доверительный интервал для математического ожидания при доверительной вероятности gamma;
# 4) доверительный интервал для среднего квадратического отклонения для того же gamma.
# Вариант 1: gamma = 0.95, данные выборки занесены ниже.

#Я оцениваю среднее, дисперсию и строю доверительный интервал. Если sigma(среднее квадратическое отклонение) известна - нормальное распределение. Если sigma неизвестна и выборка малая - Стьюдент.

# data - данные из варианта, по условию они нормальные.
DATA_TASK4 = [18.3, 15.5, 24.5, 24.7, 18.0, 13.3, 15.4, 10.1,
              23.1, 19.3, 5.7, 11.6, 14.3, -4.5, 20.3, 32.3]

def main(data = DATA_TASK4, y = 0.95)
  # y - доверительная вероятность.
  puts(data.max - data.min)
  # x - среднее по выборке.
  x = StatisticsHelper.mean(data)
  puts format("Среднее = %.3f", x)
  # D - дисперсия, потом делаю ее исправленной.
  d = StatisticsHelper.variance(data, sample: true, center: x)
  puts format("Дисперсия = %.3f", d)
  d *= data.length.to_f / (data.length - 1)
  puts format("Дисперсия исправленная = %.3f", d)
  # Gran - число из таблицы Лапласа для интервала.
  gran = Laplas.get_parm(y / 2.0)
  puts format("(%.3f;%.3f)", x - gran, x + gran)
  # q - число из таблицы для интервала по отклонению.
  q = 0.66
  puts format("(%.3f;%.3f)", x * (1 - q), x * (1 + q))
end

