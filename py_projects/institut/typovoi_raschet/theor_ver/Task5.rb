def main(data = DATA_TASK5, y = 0.99, s = 9)
  # y - доверительная вероятность из условия.
  # s - известное sigma из условия.
  # x - среднее по выборке, от него строится интервал.
  x = StatisticsHelper.mean(data)
  puts x
  # gran - сколько отступаем от среднего в обе стороны.
  gran = Laplas.get_parm(y / 2.0) * s / Math.sqrt(data.length)
  puts format("(%.3f; %.3f)", x - gran, x + gran)
end

