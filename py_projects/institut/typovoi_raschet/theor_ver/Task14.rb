def main(data_x = X_TASK14, data_y = Y_TASK14, alpha = 0.01)
  # X и Y - средние значения этих выборок.
  x_mean = StatisticsHelper.mean(data_x)
  puts x_mean
  y_mean = StatisticsHelper.mean(data_y)
  puts y_mean
  nx = data_x.length
  ny = data_y.length
  sx2 = StatisticsHelper.variance(data_x, sample: true)
  sy2 = StatisticsHelper.variance(data_y, sample: true)
  pooled = ((nx - 1) * sx2 + (ny - 1) * sy2) / (nx + ny - 2).to_f
  # stata - t-критерий; p_val здесь считаю через нормальное приближение.
  stata = (x_mean - y_mean) / Math.sqrt(pooled * (1.0 / nx + 1.0 / ny))
  p_val = 2.0 * (1.0 - StatisticsHelper.normal_cdf(stata.abs))
  puts stata
  puts p_val
  puts(p_val > alpha ? "– нет оснований отвергнуть гипотезу" : "– гипотезу отвергают.")
end

