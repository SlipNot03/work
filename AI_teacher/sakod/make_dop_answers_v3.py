def read_docx(path):
    with ZipFile(path) as z:
        root = ET.fromstring(z.read("word/document.xml"))
    result = []
    for par in root.findall(".//w:p", NS):
        text = "".join((t.text or "") for t in par.findall(".//w:t", NS)).strip()
        if text:
            result.append(text)
    return result


